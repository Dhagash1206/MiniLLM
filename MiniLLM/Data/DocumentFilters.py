"""Quality, license, secret, and duplicate filters for English and code documents."""

from __future__ import annotations

import hashlib
import re

# Matches high-confidence credential formats; files containing any are dropped entirely.
SECRET_PATTERNS = [
    re.compile(r"AKIA[0-9A-Z]{16}"),  # AWS access key id
    re.compile(r"(?i)aws_secret_access_key\s*[:=]\s*['\"][A-Za-z0-9/+=]{40}['\"]"),
    re.compile(r"-----BEGIN (?:RSA |EC |DSA |OPENSSH |PGP )?PRIVATE KEY-----"),
    re.compile(r"gh[pousr]_[A-Za-z0-9]{36,}"),  # GitHub tokens
    re.compile(r"github_pat_[A-Za-z0-9_]{60,}"),
    re.compile(r"xox[baprs]-[A-Za-z0-9-]{10,}"),  # Slack tokens
    re.compile(r"AIza[0-9A-Za-z\-_]{35}"),  # Google API key
    re.compile(r"sk_live_[0-9a-zA-Z]{24,}"),  # Stripe live key
    re.compile(r"sk-(?:proj-)?[A-Za-z0-9_-]{32,}"),  # OpenAI-style keys
    re.compile(r"sk-ant-[A-Za-z0-9_-]{32,}"),
    re.compile(r"hf_[A-Za-z0-9]{34,}"),  # Hugging Face tokens
    re.compile(r"eyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}"),  # JWT
    re.compile(
        r"(?i)\b(?:password|passwd|pwd|secret|api_key|apikey|access_token|auth_token)\b\s*[:=]\s*['\"][^'\"\s]{8,}['\"]"
    ),
    re.compile(r"(?i)(?:postgres|mysql|mongodb(?:\+srv)?)://[^:\s/]+:[^@\s/]+@"),  # DB URL with password
]

PERMISSIVE_LICENSES = {
    "mit", "apache-2.0", "bsd-2-clause", "bsd-3-clause", "bsd-3-clause-clear", "isc",
    "unlicense", "cc0-1.0", "0bsd", "zlib", "mit-0", "bsl-1.0", "wtfpl", "python-2.0",
    "psf-2.0", "artistic-2.0", "upl-1.0", "ms-pl", "x11", "postgresql", "ncsa",
}

# Copyleft/proprietary headers inside a file override the repo-level license tag.
RESTRICTIVE_HEADER = re.compile(
    r"(?i)(GNU (?:Affero |Lesser )?General Public License|\bA?GPL-?v?[23]\b|\bLGPL\b|"
    r"All rights reserved\.?\s*(?:Unauthorized|Proprietary|Confidential)|"
    r"\bproprietary and confidential\b|Creative Commons Attribution-(?:NonCommercial|ShareAlike))"
)

AUTOGEN_MARKERS = re.compile(
    r"(?i)(auto-?generated|do not edit|generated by (?:the )?(?:protoc|swagger|openapi|django \d|jooq|sqlc)|"
    r"this file was generated|@generated)"
)


def normalized_hash(text: str) -> bytes:
    # Whitespace/case-insensitive exact-dup detection; 8 bytes keeps millions of hashes cheap in RAM.
    normalized = " ".join(text.lower().split())
    return hashlib.blake2b(normalized.encode("utf-8", errors="ignore"), digest_size=8).digest()


class Deduplicator:
    def __init__(self) -> None:
        self.seen_hashes: set[bytes] = set()

    def is_duplicate(self, text: str) -> bool:
        digest = normalized_hash(text)
        if digest in self.seen_hashes:
            return True
        self.seen_hashes.add(digest)
        return False


def contains_secret(text: str) -> bool:
    return any(pattern.search(text) for pattern in SECRET_PATTERNS)


def english_quality_ok(text: str, record: dict | None = None) -> bool:
    record = record or {}
    if record.get("language_score") is not None and record["language_score"] < 0.9:
        return False
    if record.get("int_score") is not None and record["int_score"] < 3:
        return False

    words = text.split()
    if not 50 <= len(words) <= 100_000:
        return False
    mean_word_length = sum(len(word) for word in words) / len(words)
    if not 3 <= mean_word_length <= 10:
        return False

    alpha_chars = sum(char.isalpha() for char in text)
    if alpha_chars / max(len(text), 1) < 0.6:
        return False

    lines = [line.strip() for line in text.splitlines() if line.strip()]
    if lines:
        # Boilerplate/navigation pages repeat the same lines many times.
        if 1 - len(set(lines)) / len(lines) > 0.3:
            return False
        bullet_lines = sum(line.startswith(("•", "-", "*", "·")) for line in lines)
        if bullet_lines / len(lines) > 0.9:
            return False
        ellipsis_lines = sum(line.endswith(("...", "…")) for line in lines)
        if ellipsis_lines / len(lines) > 0.3:
            return False
    return True


def license_ok(record: dict) -> bool:
    licenses = record.get("max_stars_repo_licenses") or record.get("licenses") or []
    if isinstance(licenses, str):
        licenses = [licenses]
    if not licenses:
        return False
    return all(license_name.lower() in PERMISSIVE_LICENSES for license_name in licenses)


def code_quality_ok(text: str, record: dict | None = None) -> bool:
    record = record or {}
    if not 100 <= len(text) <= 100_000:
        return False

    lines = text.splitlines()
    if not lines:
        return False
    line_lengths = [len(line) for line in lines]
    max_line_length = record.get("max_line_length") or max(line_lengths)
    avg_line_length = record.get("avg_line_length") or (sum(line_lengths) / len(lines))
    alphanum_fraction = record.get("alphanum_fraction")
    if alphanum_fraction is None:
        alphanum_fraction = sum(char.isalnum() for char in text) / len(text)

    # Minified JS / data blobs have huge lines and few alphanumerics.
    if max_line_length > 1000 or avg_line_length > 100 or alphanum_fraction < 0.25:
        return False

    header = "\n".join(lines[:30])
    if AUTOGEN_MARKERS.search(header):
        return False
    if RESTRICTIVE_HEADER.search(header):
        return False

    # Mostly-data files (huge INSERT dumps, number arrays) teach little.
    digit_fraction = sum(char.isdigit() for char in text) / len(text)
    if digit_fraction > 0.4:
        return False
    return True


def code_document_ok(text: str, record: dict) -> bool:
    return license_ok(record) and code_quality_ok(text, record) and not contains_secret(text)
