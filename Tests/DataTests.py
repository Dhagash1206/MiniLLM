GOOD_CODE = "import os\n\n\ndef list_files(path):\n    \"\"\"Return file names.\"\"\"\n    return sorted(os.listdir(path))\n" * 3
MIT_RECORD = {"max_stars_repo_licenses": ["MIT"]}


def test_secret_detection():
    assert contains_secret('AWS_KEY = "AKIAABCDEFGHIJKLMNOP"')
    assert contains_secret("token = 'ghp_" + "a" * 36 + "'")
    assert contains_secret('password = "hunter2hunter2"')
    assert contains_secret("-----BEGIN RSA PRIVATE KEY-----")
    assert not contains_secret("password = os.environ['DB_PASSWORD']")


def test_license_and_code_filters():
    assert license_ok(MIT_RECORD)
    assert not license_ok({"max_stars_repo_licenses": ["GPL-3.0"]})
    assert not license_ok({"max_stars_repo_licenses": []})
    assert code_document_ok(GOOD_CODE, MIT_RECORD)
    gpl_header = "# This program is free software under the GNU General Public License\n" + GOOD_CODE
    assert not code_document_ok(gpl_header, MIT_RECORD)
    minified = "var a=1;" * 300
    assert not code_document_ok(minified, MIT_RECORD)
    assert not code_document_ok("# Code generated by protoc. DO NOT EDIT.\n" + GOOD_CODE, MIT_RECORD)


def test_english_filter_and_dedup():
    article = " ".join(["Photosynthesis converts light energy into chemical energy in plants."] * 1) + " " + \
        " ".join(f"Sentence number {index} explains another idea about cells and energy." for index in range(20))
    assert english_quality_ok(article, {"language_score": 0.95, "int_score": 3})
